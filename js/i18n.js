  var LANG_KEY = "vox-lang";

  function applyLang(lang) {
    var dict = I18N[lang] || I18N.en;
    var htmlLang = lang === "zh" ? "zh-CN" : (lang === "es" ? "es" : "en");
    document.documentElement.lang = htmlLang;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (dict[key] != null) el.innerHTML = dict[key];
    });

    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-ph");
      if (dict[key] != null) el.setAttribute("placeholder", dict[key]);
    });

    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-aria");
      if (dict[key] != null) el.setAttribute("aria-label", dict[key]);
    });

    document.querySelectorAll("[data-i18n-label]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-label");
      if (dict[key] != null) el.setAttribute("label", dict[key]);
    });

    document.querySelectorAll("[data-i18n-value]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-value");
      if (dict[key] != null) el.setAttribute("value", dict[key]);
    });

    if (dict["title"]) document.title = dict["title"];
    var meta = document.querySelector('meta[name="description"]');
    if (meta && dict["meta_description"]) meta.setAttribute("content", dict["meta_description"]);

    var sel = document.getElementById("langSelect");
    if (sel && sel.value !== lang) sel.value = lang;

    try {
      window.dispatchEvent(new CustomEvent("vox-lang-change", { detail: lang }));
    } catch (e) {}
  }

  function init() {
    var stored = null;
    try { stored = localStorage.getItem(LANG_KEY); } catch (e) {}
    applyLang(stored || "en");

    var sel = document.getElementById("langSelect");
    if (sel) {
      sel.addEventListener("change", function () {
        try { localStorage.setItem(LANG_KEY, sel.value); } catch (e) {}
        applyLang(sel.value);
      });
    }
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
